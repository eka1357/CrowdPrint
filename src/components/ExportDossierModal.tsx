'use client';

import React, { useState } from 'react';
import { motion, AnimatePresence } from 'motion/react';
import {
  EventBrief,
  ResolvedArtist,
  SynthesizedSponsor,
  CommercialRuleRejection,
  QlooAnchorVenue,
} from '@/lib/types';
import {
  Printer,
  Copy,
  Check,
  X,
  Radio,
  Building2,
  Mail,
  MapPin,
} from 'lucide-react';

interface ExportDossierModalProps {
  isOpen: boolean;
  onClose: () => void;
  brief: EventBrief;
  resolvedArtists: ResolvedArtist[];
  approvedSponsors: SynthesizedSponsor[];
  rejectedSponsors: CommercialRuleRejection[];
  anchorVenues?: QlooAnchorVenue[];
  tasteTags: string[];
}

export function ExportDossierModal({
  isOpen,
  onClose,
  brief,
  resolvedArtists,
  approvedSponsors,
  rejectedSponsors,
  anchorVenues = [],
  tasteTags = [],
}: ExportDossierModalProps) {
  const [copied, setCopied] = useState(false);

  // Generate complete Markdown text for 1-click clipboard copy
  const generateMarkdown = (): string => {
    const timestamp = new Date().toLocaleDateString('en-US', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    });

    let md = `# CROWDPRINT SPONSORSHIP DOSSIER\n`;
    md += `**Event Brief:** ${brief.name}\n`;
    md += `**Metro Market:** ${brief.city}\n`;
    md += `**Expected Attendance:** ${brief.expectedAttendance ? brief.expectedAttendance.toLocaleString() : '3,500'}\n`;
    md += `**Budget Floor:** $${((brief.constraints.minBudgetTier || 50000) / 1000).toFixed(0)}k\n`;
    md += `**Intelligence Engine:** Qloo Taste Graph API (250M+ Entities)\n`;
    md += `**Generated Date:** ${timestamp}\n\n`;

    md += `---\n\n`;

    // 1. Lineup
    md += `## 1. Grounded Lineup Entities (Qloo Graph)\n\n`;
    md += `| Artist | Qloo Entity ID | Disambiguation / Genre | Pop % |\n`;
    md += `| :--- | :--- | :--- | :--- |\n`;
    resolvedArtists.forEach((a) => {
      const pop = a.disambiguationScore ? `${Math.round(a.disambiguationScore * 100)}%` : '95%';
      const genres = a.genres && a.genres.length > 0 ? a.genres.join(', ') : 'Musical Artist';
      md += `| **${a.resolvedName}** | \`${a.entityId}\` | ${genres} | ${pop} |\n`;
    });
    md += `\n`;

    // 2. Taste Signals
    if (tasteTags.length > 0) {
      md += `## 2. Empirical Audience Taste Signals\n\n`;
      md += `Top correlated cultural affinities identified across attendee demographic:\n`;
      md += `> ${tasteTags.slice(0, 8).map((t) => `\`${t}\``).join(' • ')}\n\n`;
    }

    // 3. Top Approved Sponsors
    md += `## 3. Recommended Commercial Sponsors (Empirical Qloo Overlap)\n\n`;
    approvedSponsors.forEach((s, idx) => {
      md += `### #${idx + 1}. ${s.name} — ${s.affinityScore}% Audience Affinity\n`;
      md += `- **Categories:** ${s.categories.join(', ')}\n`;
      md += `- **Qloo Entity ID:** \`${s.entityId}\`\n`;
      if (s.sharedTags && s.sharedTags.length > 0) {
        md += `- **Shared Taste Signals:** ${s.sharedTags.join(', ')}\n`;
      }
      if (s.activations && s.activations.length > 0) {
        md += `\n**Proposed Activations:**\n`;
        s.activations.forEach((act) => {
          md += `- **${act.title}**: ${act.creativeExtension} *(Signal: ${act.qlooSignalCited}, Zone: ${act.suggestedZone || 'Festival Grounds'}${act.estimatedReach ? `, Reach: ${act.estimatedReach}` : ''})*\n`;
        });
      }
      if (s.pitchEmail) {
        md += `\n**Executive Pitch Draft:**\n`;
        md += `> **Subject:** ${s.pitchEmail.subjectLine}\n`;
        md += `> **Target:** ${s.pitchEmail.targetPersona}\n`;
        md += `> **Value Proposition:** ${s.pitchEmail.valueProposition}\n\n`;
        md += `\`\`\`\n${s.pitchEmail.emailBody}\n\`\`\`\n\n`;
      }
      md += `---\n\n`;
    });

    // 4. Anchor Venues
    if (anchorVenues.length > 0) {
      md += `## 4. Local Experiential Activation Venues (\`urn:entity:place\`)\n\n`;
      anchorVenues.forEach((v) => {
        md += `- **${v.name}** (${v.category || 'Activation Space'})\n`;
        md += `  - Address: ${v.address || brief.city}\n`;
        md += `  - Entity ID: \`${v.entityId}\`\n`;
        if (v.neighborhood) md += `  - Neighborhood: ${v.neighborhood}\n`;
      });
      md += `\n`;
    }

    // 5. Commercial Interceptions
    if (rejectedSponsors.length > 0) {
      md += `## 5. Commercial Guardrails Interceptions Audit\n\n`;
      md += `| Intercepted Brand | Triggered Rule | Reason Code | Deterministic Explanation |\n`;
      md += `| :--- | :--- | :--- | :--- |\n`;
      rejectedSponsors.forEach((r) => {
        md += `| **${r.brand.name}** | \`${r.ruleTriggered}\` | ${r.reasonCode} | ${r.explanation} |\n`;
      });
      md += `\n`;
    }

    md += `\n*Confidential report generated by Crowdprint autonomously via Qloo Taste AI™ Graph API.*\n`;
    return md;
  };

  const handleCopy = async () => {
    try {
      const text = generateMarkdown();
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (err) {
      console.error('Failed to copy dossier markdown:', err);
    }
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <AnimatePresence>
      {isOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-2 sm:p-4 md:p-6 overflow-y-auto">
          {/* Backdrop */}
          <motion.div
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0 }}
            onClick={onClose}
            className="fixed inset-0 bg-black/85 backdrop-blur-md no-print"
          />

          {/* Modal Container */}
          <motion.div
            initial={{ opacity: 0, scale: 0.96, y: 12 }}
            animate={{ opacity: 1, scale: 1, y: 0 }}
            exit={{ opacity: 0, scale: 0.96, y: 12 }}
            transition={{ type: 'spring', duration: 0.35, bounce: 0.15 }}
            className="relative w-full max-w-5xl bg-zinc-950 border border-zinc-800 rounded-2xl shadow-2xl overflow-hidden z-10 flex flex-col my-4 max-h-[92vh] print-dossier-container"
          >
            {/* Modal Actions Bar (Sticky Header) */}
            <div className="px-6 py-3.5 border-b border-zinc-800 bg-zinc-900/90 backdrop-blur-md flex items-center justify-between shrink-0 no-print">
              <div className="flex items-center gap-3">
                <div className="w-8 h-8 rounded-lg bg-emerald-500/10 border border-emerald-500/30 flex items-center justify-center text-emerald-400">
                  <Radio className="w-4 h-4 animate-pulse" />
                </div>
                <div>
                  <h2 className="text-sm font-bold text-white flex items-center gap-2 font-mono">
                    <span>Executive Sponsorship Dossier</span>
                    <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-zinc-800 text-emerald-400 border border-emerald-800/40">
                      Print-Ready
                    </span>
                  </h2>
                  <p className="text-xs text-zinc-400 font-mono">
                    {brief.name} • Grounded via Qloo Taste Graph API
                  </p>
                </div>
              </div>

              <div className="flex items-center gap-2">
                {/* Copy Markdown Button */}
                <button
                  type="button"
                  onClick={handleCopy}
                  className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-zinc-850 hover:bg-zinc-800 text-xs font-mono text-zinc-200 border border-zinc-700 transition-colors cursor-pointer"
                  title="Copy complete markdown text to clipboard"
                >
                  {copied ? (
                    <>
                      <Check className="w-3.5 h-3.5 text-emerald-400" />
                      <span className="text-emerald-400 font-semibold">Copied MD!</span>
                    </>
                  ) : (
                    <>
                      <Copy className="w-3.5 h-3.5 text-zinc-400" />
                      <span>Copy Markdown</span>
                    </>
                  )}
                </button>

                {/* Print / Save PDF Button */}
                <button
                  type="button"
                  onClick={handlePrint}
                  className="flex items-center gap-1.5 px-3.5 py-1.5 rounded-lg bg-emerald-500 hover:bg-emerald-400 text-xs font-mono font-bold text-black transition-all shadow-md shadow-emerald-500/20 cursor-pointer"
                  title="Open Print Dialog to Save as PDF"
                >
                  <Printer className="w-3.5 h-3.5 text-black" />
                  <span>Print / Save PDF</span>
                </button>

                {/* Close Button */}
                <button
                  type="button"
                  onClick={onClose}
                  className="p-1.5 rounded-lg text-zinc-400 hover:text-white hover:bg-zinc-800 transition-colors cursor-pointer ml-1"
                  title="Close (Esc)"
                >
                  <X className="w-4 h-4" />
                </button>
              </div>
            </div>

            {/* Dossier Document Body */}
            <div className="p-6 sm:p-10 overflow-y-auto space-y-8 font-sans text-zinc-200 dossier-content">
              {/* Executive Header Block */}
              <div className="border-b border-zinc-800 pb-6 space-y-3">
                <div className="flex items-center justify-between text-xs font-mono text-zinc-400">
                  <span className="px-2 py-0.5 rounded bg-zinc-900 border border-zinc-800 text-emerald-400 font-semibold tracking-wider uppercase">
                    Commercial Intelligence Memorandum
                  </span>
                  <span>{new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}</span>
                </div>

                <h1 className="text-2xl sm:text-3xl font-extrabold tracking-tight text-white font-sans">
                  {brief.name}
                </h1>
                <p className="text-sm text-zinc-400 max-w-2xl font-mono">
                  {brief.tagline || 'Strategic Brand Sponsorship & Local Activation Dossier'}
                </p>

                {/* Meta stats bar */}
                <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 pt-3">
                  <div className="p-2.5 rounded-lg bg-zinc-900/60 border border-zinc-850">
                    <div className="text-[10px] font-mono uppercase text-zinc-400">Metro Market</div>
                    <div className="text-xs font-bold font-mono text-zinc-100 mt-0.5 truncate">{brief.city}</div>
                  </div>
                  <div className="p-2.5 rounded-lg bg-zinc-900/60 border border-zinc-850">
                    <div className="text-[10px] font-mono uppercase text-zinc-400">Audience Scale</div>
                    <div className="text-xs font-bold font-mono text-zinc-100 mt-0.5">
                      {brief.expectedAttendance ? brief.expectedAttendance.toLocaleString() : '3,500'} Attendees
                    </div>
                  </div>
                  <div className="p-2.5 rounded-lg bg-zinc-900/60 border border-zinc-850">
                    <div className="text-[10px] font-mono uppercase text-zinc-400">Min Budget Floor</div>
                    <div className="text-xs font-bold font-mono text-amber-300 mt-0.5">
                      ${((brief.constraints.minBudgetTier || 50000) / 1000).toFixed(0)}k USD
                    </div>
                  </div>
                  <div className="p-2.5 rounded-lg bg-zinc-900/60 border border-zinc-850">
                    <div className="text-[10px] font-mono uppercase text-zinc-400">Graph Grounding</div>
                    <div className="text-xs font-bold font-mono text-emerald-400 mt-0.5">Qloo API (Verified)</div>
                  </div>
                </div>
              </div>

              {/* Section 1: Resolved Lineup */}
              <div className="space-y-3">
                <div className="flex items-center gap-2">
                  <span className="w-2 h-2 rounded-full bg-emerald-400" />
                  <h3 className="text-sm font-mono font-bold uppercase tracking-wider text-zinc-100">
                    1. Grounded Lineup Entities (Qloo Graph)
                  </h3>
                </div>

                <div className="overflow-x-auto rounded-xl border border-zinc-800 bg-zinc-950/80">
                  <table className="w-full text-left text-xs font-mono">
                    <thead className="bg-zinc-900/80 text-zinc-400 border-b border-zinc-800">
                      <tr>
                        <th className="p-3">Artist Name</th>
                        <th className="p-3">Qloo Entity UUID</th>
                        <th className="p-3">Disambiguation / Genres</th>
                        <th className="p-3 text-right">Popularity</th>
                      </tr>
                    </thead>
                    <tbody className="divide-y divide-zinc-850">
                      {resolvedArtists.map((artist) => (
                        <tr key={artist.entityId} className="hover:bg-zinc-900/40">
                          <td className="p-3 font-bold text-white flex items-center gap-1.5">
                            <span className="w-1.5 h-1.5 rounded-full bg-emerald-400 shrink-0" />
                            <span>{artist.resolvedName}</span>
                          </td>
                          <td className="p-3 text-zinc-400 font-mono text-[11px] select-all">
                            {artist.entityId}
                          </td>
                          <td className="p-3 text-zinc-300">
                            {artist.genres && artist.genres.length > 0
                              ? artist.genres.join(' • ')
                              : 'Musical Artist'}
                          </td>
                          <td className="p-3 text-right text-emerald-400 font-bold">
                            {artist.disambiguationScore ? `${Math.round(artist.disambiguationScore * 100)}%` : '95%'}
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              </div>

              {/* Section 2: Audience Taste Signals */}
              {tasteTags.length > 0 && (
                <div className="space-y-3">
                  <div className="flex items-center gap-2">
                    <span className="w-2 h-2 rounded-full bg-purple-400" />
                    <h3 className="text-sm font-mono font-bold uppercase tracking-wider text-zinc-100">
                      2. Empirical Audience Taste Profile
                    </h3>
                  </div>
                  <div className="p-4 rounded-xl bg-zinc-900/40 border border-zinc-800 flex flex-wrap gap-2">
                    {tasteTags.map((tag) => (
                      <span
                        key={tag}
                        className="px-2.5 py-1 rounded-lg bg-zinc-950 text-purple-300 border border-purple-900/50 text-xs font-mono"
                      >
                        {tag}
                      </span>
                    ))}
                  </div>
                </div>
              )}

              {/* Section 3: Recommended Commercial Sponsors */}
              <div className="space-y-4">
                <div className="flex items-center justify-between">
                  <div className="flex items-center gap-2">
                    <span className="w-2 h-2 rounded-full bg-emerald-400" />
                    <h3 className="text-sm font-mono font-bold uppercase tracking-wider text-zinc-100">
                      3. Top Approved Brand Sponsors ({approvedSponsors.length})
                    </h3>
                  </div>
                  <span className="text-xs font-mono text-zinc-400">
                    Ranked by empirical audience affinity
                  </span>
                </div>

                <div className="space-y-4">
                  {approvedSponsors.map((sponsor, idx) => (
                    <div
                      key={sponsor.entityId}
                      className="p-5 rounded-xl bg-zinc-900/40 border border-zinc-800/80 space-y-4"
                    >
                      {/* Sponsor Header */}
                      <div className="flex flex-wrap items-start justify-between gap-2 border-b border-zinc-850 pb-3">
                        <div>
                          <div className="flex items-center gap-2">
                            <span className="text-xs font-mono font-bold text-zinc-400">#{idx + 1}</span>
                            <h4 className="text-lg font-bold text-white font-sans">{sponsor.name}</h4>
                            <span className="px-2 py-0.5 rounded text-[10px] font-mono bg-zinc-800 text-zinc-300">
                              {sponsor.categories.join(', ')}
                            </span>
                          </div>
                          <p className="text-[11px] font-mono text-zinc-400 mt-1 select-all">
                            Qloo Entity: {sponsor.entityId}
                          </p>
                        </div>

                        <div className="text-right">
                          <div className="text-xl font-bold font-mono text-emerald-400">
                            {sponsor.affinityScore}%
                          </div>
                          <div className="text-[10px] font-mono text-zinc-400 uppercase">
                            Qloo Affinity Score
                          </div>
                        </div>
                      </div>

                      {/* Shared Taste Signals */}
                      {sponsor.sharedTags && sponsor.sharedTags.length > 0 && (
                        <div>
                          <div className="text-[10px] font-mono uppercase text-zinc-400 mb-1">
                            Shared Cultural Signals:
                          </div>
                          <div className="flex flex-wrap gap-1.5">
                            {sponsor.sharedTags.map((tag) => (
                              <span
                                key={tag}
                                className="px-2 py-0.5 rounded bg-zinc-950 text-zinc-300 border border-zinc-800 text-[11px] font-mono"
                              >
                                {tag}
                              </span>
                            ))}
                          </div>
                        </div>
                      )}

                      {/* Proposed Activations */}
                      {sponsor.activations && sponsor.activations.length > 0 && (
                        <div className="space-y-2 pt-2">
                          <div className="text-[10px] font-mono uppercase text-zinc-400">
                            Custom Experiential Activations:
                          </div>
                          <div className="grid grid-cols-1 md:grid-cols-2 gap-2.5">
                            {sponsor.activations.map((act, aIdx) => (
                              <div
                                key={aIdx}
                                className="p-3 rounded-lg bg-zinc-950/70 border border-zinc-850 space-y-1.5"
                              >
                                <div className="text-xs font-bold text-zinc-200">{act.title}</div>
                                <p className="text-xs text-zinc-400 leading-relaxed">{act.creativeExtension}</p>
                                <div className="flex items-center justify-between text-[10px] font-mono text-zinc-400 pt-1 border-t border-zinc-900">
                                  <span className="text-emerald-400 truncate max-w-[150px]">{act.qlooSignalCited}</span>
                                  <span className="text-amber-400">{act.suggestedZone || act.estimatedReach || 'Festival Ground'}</span>
                                </div>
                              </div>
                            ))}
                          </div>
                        </div>
                      )}

                      {/* Executive Pitch Email Draft */}
                      {sponsor.pitchEmail && (
                        <div className="space-y-1.5 pt-2">
                          <div className="text-[10px] font-mono uppercase text-zinc-400 flex items-center gap-1.5">
                            <Mail className="w-3 h-3 text-emerald-400" />
                            <span>Ready-to-Send Executive Pitch Draft</span>
                          </div>
                          <div className="p-3.5 rounded-lg bg-zinc-950 border border-zinc-850 text-xs font-mono space-y-2">
                            <div className="text-zinc-300">
                              <span className="text-zinc-400">Subject: </span>
                              <span className="text-white font-semibold">{sponsor.pitchEmail.subjectLine}</span>
                            </div>
                            <div className="text-zinc-400 text-[11px]">
                              <span>Target: </span>
                              <span className="text-zinc-300">{sponsor.pitchEmail.targetPersona}</span>
                            </div>
                            <p className="text-zinc-400 text-xs leading-relaxed whitespace-pre-line border-t border-zinc-900 pt-2">
                              {sponsor.pitchEmail.emailBody}
                            </p>
                          </div>
                        </div>
                      )}
                    </div>
                  ))}
                </div>
              </div>

              {/* Section 4: Local Activation Venues */}
              {anchorVenues.length > 0 && (
                <div className="space-y-3">
                  <div className="flex items-center gap-2">
                    <span className="w-2 h-2 rounded-full bg-blue-400" />
                    <h3 className="text-sm font-mono font-bold uppercase tracking-wider text-zinc-100">
                      4. Local Activation Venues (Qloo Places Graph)
                    </h3>
                  </div>

                  <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 gap-3">
                    {anchorVenues.map((venue) => (
                      <div
                        key={venue.entityId}
                        className="p-3.5 rounded-xl bg-zinc-900/40 border border-zinc-800 space-y-1.5"
                      >
                        <div className="text-xs font-bold text-white flex items-center gap-1.5">
                          <Building2 className="w-3.5 h-3.5 text-blue-400 shrink-0" />
                          <span className="truncate">{venue.name}</span>
                        </div>
                        <div className="text-xs text-zinc-400 flex items-start gap-1">
                          <MapPin className="w-3 h-3 text-zinc-400 shrink-0 mt-0.5" />
                          <span className="text-[11px] leading-tight">{venue.address || brief.city}</span>
                        </div>
                        <div className="flex items-center justify-between text-[10px] font-mono text-zinc-400 pt-1 border-t border-zinc-850">
                          <span>{venue.category || 'Activation Venue'}</span>
                          <span className="text-blue-400 font-semibold">{venue.neighborhood || brief.city}</span>
                        </div>
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {/* Section 5: Commercial Guardrails Audit Log */}
              {rejectedSponsors.length > 0 && (
                <div className="space-y-3">
                  <div className="flex items-center gap-2">
                    <span className="w-2 h-2 rounded-full bg-red-400" />
                    <h3 className="text-sm font-mono font-bold uppercase tracking-wider text-zinc-100">
                      5. Commercial Guardrails Interceptions Audit ({rejectedSponsors.length})
                    </h3>
                  </div>

                  <div className="overflow-x-auto rounded-xl border border-zinc-800 bg-zinc-950/80">
                    <table className="w-full text-left text-xs font-mono">
                      <thead className="bg-zinc-900/80 text-zinc-400 border-b border-zinc-800">
                        <tr>
                          <th className="p-3">Candidate Brand</th>
                          <th className="p-3">Triggered Rule</th>
                          <th className="p-3">Reason Code</th>
                          <th className="p-3">Deterministic Reasoning</th>
                        </tr>
                      </thead>
                      <tbody className="divide-y divide-zinc-850">
                        {rejectedSponsors.map((rej) => (
                          <tr key={rej.brand.entityId} className="hover:bg-zinc-900/40">
                            <td className="p-3 font-bold text-red-300">
                              {rej.brand.name}
                            </td>
                            <td className="p-3">
                              <span className="px-1.5 py-0.5 rounded bg-zinc-900 text-zinc-300 border border-zinc-800 text-[10px]">
                                {rej.ruleTriggered}
                              </span>
                            </td>
                            <td className="p-3 text-zinc-400 font-mono text-[11px]">
                              {rej.reasonCode}
                            </td>
                            <td className="p-3 text-zinc-400 text-[11px] leading-relaxed">
                              {rej.explanation}
                            </td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                </div>
              )}

              {/* Footer Note */}
              <div className="pt-6 border-t border-zinc-850 text-center text-xs font-mono text-zinc-400 space-y-1">
                <div>Autonomous Commercial Strategy generated by Crowdprint.</div>
                <div>Grounded with deterministic compliance against Qloo Taste AI™ Graph API.</div>
              </div>
            </div>
          </motion.div>
        </div>
      )}
    </AnimatePresence>
  );
}

export default ExportDossierModal;
