/**
 * Crowdprint Core Type Definitions
 * Specification: docs/AGENTS.md, docs/ARCHITECHTURE.md, docs/FEATURES.md
 */

export interface ResolvedArtist {
  inputName: string;
  resolvedName: string;
  entityId: string; // e.g., "urn:entity:artist:..."
  verified: boolean;
  disambiguationScore?: number;
  genres?: string[];
}

export interface QlooBrandCandidate {
  entityId: string; // e.g., "urn:entity:brand:..." or Qloo UUID
  name: string;
  affinityScore: number; // Raw Qloo affinity score (0-100 or 0.0-1.0 normalized to 0-100)
  categories: string[];
  sharedTags: string[];
  rawQueryUrl: string; // Sanitized Qloo query URL for the Evidence Drawer
  description?: string;
  typicalTier?: 'TIER_1_HEADLINE' | 'TIER_2_STAGE' | 'TIER_3_SUPPORTING' | 'BOUTIQUE';
}

export interface QlooAnchorVenue {
  entityId: string;
  name: string;
  address?: string;
  category?: string;
  popularity?: number;
  neighborhood?: string;
}

export interface CommercialConstraints {
  minBudgetTier?: number; // e.g., 50000, 75000, 150000 USD
  blockedCategories: string[]; // e.g., ["Alcohol", "Hard Liquor", "Fast Fashion", "Energy Drinks", "Crypto", "Sportswear"]
  lockedCompetitors: string[]; // e.g., ["Nike", "Adidas"]
  ageRestriction?: 'ALL_AGES' | '18_PLUS' | '21_PLUS';
  ecoConsciousOnly?: boolean;
}

export type RejectionReasonCode =
  | 'CATEGORY_EXCLUSION'
  | 'COMPETITOR_LOCK'
  | 'AGE_RESTRICTION'
  | 'BUDGET_MISMATCH'
  | 'ECO_NON_COMPLIANT';

export interface CommercialRuleRejection {
  brand: QlooBrandCandidate;
  reasonCode: RejectionReasonCode;
  explanation: string;
  ruleTriggered: string;
}

export interface FilteredSponsorResult {
  approved: QlooBrandCandidate[];
  rejected: CommercialRuleRejection[];
}

export interface ActivationIdea {
  id: string;
  title: string;
  /**
   * Verified tag or cross-domain entity from Qloo Taste Graph.
   * Rendered with an Emerald (#10B981) badge.
   */
  qlooSignalCited: string;
  /**
   * Creative operational execution idea generated by the LLM.
   * Rendered with an Amber (#F59E0B) badge.
   */
  creativeExtension: string;
  suggestedZone?: string;
  estimatedReach?: string;
}

export interface SponsorPitch {
  sponsorName: string;
  targetPersona: string;
  subjectLine: string;
  emailBody: string;
  valueProposition: string;
}

export interface SynthesizedSponsor extends QlooBrandCandidate {
  activations: ActivationIdea[];
  pitchEmail: SponsorPitch;
  evidenceNotes?: string;
}

export interface PlainLlmSponsor {
  name: string;
  category: string;
  predictedReason: string;
  isGenericFortune500: boolean;
}

export interface LlmDiffComparison {
  plainLlmSponsors: PlainLlmSponsor[];
  jaccardDivergenceScore: number; // 0 to 100 percentage (1 - intersection/union)
  overlappingBrands: string[];
  divergenceSummary: string;
}

export type QlooExecutionMode = 'LIVE_QLOO' | 'CACHED_QLOO' | 'MOCK_FIXTURE';

export interface QlooCallTrace {
  stepId: string;
  endpoint: string;
  params: Record<string, string>;
  status: number;
  latencyMs: number;
  entitiesReturned: number;
  mode: QlooExecutionMode;
  timestamp?: string;
}

export interface EventBrief {
  id?: string;
  name: string;
  tagline?: string;
  lineup: string[];
  city: string;
  venueName?: string;
  expectedAttendance?: number;
  constraints: CommercialConstraints;
  presetId?: 'brooklyn-warehouse' | 'silver-lake-indie' | 'hackney-jazz' | 'custom';
  anchorVenues?: QlooAnchorVenue[];
}

export interface AnalyzeRequest {
  brief: EventBrief;
  forceRefresh?: boolean;
}

export interface AnalyzeResponse {
  brief: EventBrief;
  resolvedArtists: ResolvedArtist[];
  approvedSponsors: SynthesizedSponsor[];
  rejectedSponsors: CommercialRuleRejection[];
  allEvaluatedBrands?: QlooBrandCandidate[];
  plainLlmBaseline: LlmDiffComparison;
  tasteTags: string[];
  telemetryTraces: QlooCallTrace[];
  activeMode: QlooExecutionMode;
  executionDurationMs: number;
  timestamp: string;
  anchorVenues?: QlooAnchorVenue[];
}
